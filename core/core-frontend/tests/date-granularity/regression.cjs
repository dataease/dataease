const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')

const source = fs.readFileSync(path.join(__dirname, '../../src/utils/timeUitils.ts'), 'utf8')
const getRange = vm.runInNewContext(source.replace(/export const /g, 'const ') + '\ngetRange')
const local = (year, month, day, hour = 0, minute = 0, second = 0) =>
  +new Date(year, month - 1, day, hour, minute, second)
const range = (value, granularity, expected) =>
  assert.deepEqual(Array.from(getRange(value, granularity)), expected, `${value} ${granularity}`)

range('2021-00', 'y_W', [local(2021, 1, 1), local(2021, 1, 3, 23, 59, 59)])
range('2020-01', 'y_W', [local(2020, 1, 1), local(2020, 1, 5, 23, 59, 59)])
range('2018-53', 'y_W', [local(2018, 12, 31), local(2018, 12, 31, 23, 59, 59)])
range('2026-11', 'y_W', [local(2026, 3, 9), local(2026, 3, 15, 23, 59, 59)])
range('2026-10', 'y_W', [local(2026, 3, 2), local(2026, 3, 8, 23, 59, 59)])
range('2026-44', 'y_W', [local(2026, 10, 26), local(2026, 11, 1, 23, 59, 59)])
range('2026-45', 'y_W', [local(2026, 11, 2), local(2026, 11, 8, 23, 59, 59)])
range('2026/11', 'y_W', [local(2026, 3, 9), local(2026, 3, 15, 23, 59, 59)])
range('2026/3', 'y_Q', [local(2026, 7, 1), local(2026, 9, 30, 23, 59, 59)])
assert.equal(getRange('2020-00', 'y_W'), '2020-00')
assert.equal(getRange('2021-53', 'y_W'), '2021-53')
assert.equal(getRange('2026-54', 'y_W'), '2026-54')
assert.equal(getRange('2026-5', 'y_Q'), '2026-5')
assert.equal(getRange('2026//3', 'y_Q'), '2026//3')
assert.equal(getRange('2026-1/1', 'y_W'), '2026-1/1')
assert.equal(getRange('0099-1', 'y_Q'), '0099-1')
assert.equal(getRange('0099-1', 'y_W'), '0099-1')
assert.equal(getRange(null, 'y_W'), null)
console.log('date granularity regression passed:', process.env.TZ || 'system timezone')
